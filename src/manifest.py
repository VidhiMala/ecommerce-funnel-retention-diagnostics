"""
manifest.py - record and verify the exact raw files (size, row count, SHA-256).

Why: data/ is git-ignored, so a fresh clone has no data. The manifest lets anyone
prove their downloaded files are byte-for-byte the files this project analysed.

Usage (project root, venv active)
---------------------------------
    python -m src.manifest create     # once, from the verified original files
    python -m src.manifest verify     # any time; exit code 1 on any mismatch

`create` refuses to run if row counts differ from the Day 1 profile
(config.EXPECTED_ROWS) and will not overwrite an existing manifest without --force.
Files are only read.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

from src import config

MANIFEST_JSON = config.PROJECT_ROOT / "docs" / "data_manifest.json"
MANIFEST_MD = config.PROJECT_ROOT / "docs" / "data_manifest.md"
DATASET = "mkechinov/ecommerce-events-history-in-cosmetics-shop"
CHUNK = 8 * 1024 * 1024


def fingerprint(path: Path) -> dict:
    """Stream the file once: SHA-256, size in bytes, data rows (newlines minus the header)."""
    h, size, newlines, last = hashlib.sha256(), 0, 0, b""
    with open(path, "rb") as f:
        while chunk := f.read(CHUNK):
            h.update(chunk)
            size += len(chunk)
            newlines += chunk.count(b"\n")
            last = chunk[-1:]
    lines = newlines + (1 if size and last != b"\n" else 0)
    return {"file": path.name, "size_bytes": size, "rows": max(lines - 1, 0), "sha256": h.hexdigest()}


def scan(raw_dir: Path) -> list[dict]:
    out = []
    for name in config.RAW_FILES:
        p = raw_dir / name
        if not p.is_file():
            raise FileNotFoundError(f"Missing raw file: {name} (expected in {raw_dir.name}/)")
        print(f"hashing {name} ...", file=sys.stderr, flush=True)
        out.append(fingerprint(p))
    return out


def render_md(entries: list[dict]) -> str:
    rows = "\n".join(f"| `{e['file']}` | {e['size_bytes']:,} | {e['size_bytes'] / 1e6:,.1f} | {e['rows']:,} | `{e['sha256']}` |"
                     for e in entries)
    total_rows = sum(e["rows"] for e in entries)
    return f"""# Data Manifest

The exact raw files analysed in this project. Generated by `python -m src.manifest create`
from the original files verified against the Day 1 profile. Verify your copy with
`python -m src.manifest verify`.

- **Source:** Kaggle dataset `{DATASET}`
  (https://www.kaggle.com/datasets/{DATASET})
- **Files in scope:** Oct 2019 – Jan 2020 (four monthly CSVs). Other files in the dataset are not used.
- **Rows** = lines minus the header line. Total: {total_rows:,}.

| File | Size (bytes) | Size (MB) | Rows | SHA-256 |
|---|---|---|---|---|
{rows}

If `verify` reports a mismatch, the files differ from those analysed here (for example, a newer
dataset version). Do not run the pipeline on them without re-auditing.
"""


def create(raw_dir: Path, force: bool) -> int:
    if MANIFEST_JSON.exists() and not force:
        print(f"{MANIFEST_JSON.name} already exists; use `verify`, or --force to replace it.", file=sys.stderr)
        return 1
    entries = scan(raw_dir)
    bad = [e for e in entries if e["rows"] != config.EXPECTED_ROWS[e["file"]]]
    if bad:
        for e in bad:
            print(f"ROW MISMATCH {e['file']}: {e['rows']:,} vs Day 1 profile {config.EXPECTED_ROWS[e['file']]:,}",
                  file=sys.stderr)
        print("Manifest NOT written: these are not the files profiled on Day 1.", file=sys.stderr)
        return 1
    MANIFEST_JSON.write_text(json.dumps({"dataset": DATASET, "files": entries}, indent=2) + "\n", encoding="utf-8")
    MANIFEST_MD.write_text(render_md(entries), encoding="utf-8")
    print(f"Wrote {MANIFEST_JSON.relative_to(config.PROJECT_ROOT).as_posix()} and "
          f"{MANIFEST_MD.relative_to(config.PROJECT_ROOT).as_posix()}", file=sys.stderr)
    return 0


def verify(raw_dir: Path) -> int:
    if not MANIFEST_JSON.exists():
        print("No manifest yet: run `python -m src.manifest create` on the verified original files.", file=sys.stderr)
        return 1
    expected = {e["file"]: e for e in json.loads(MANIFEST_JSON.read_text(encoding="utf-8"))["files"]}
    ok = True
    for got in scan(raw_dir):
        exp = expected.get(got["file"])
        same = exp is not None and all(exp[k] == got[k] for k in ("size_bytes", "rows", "sha256"))
        ok &= same
        print(f"{'OK      ' if same else 'MISMATCH'} {got['file']}  rows {got['rows']:,}  sha256 {got['sha256'][:16]}...")
    print("All files match the manifest." if ok else "Files do NOT match the manifest. Stop and investigate.")
    return 0 if ok else 1


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(description="Create or verify the raw-data manifest.")
    p.add_argument("action", choices=["create", "verify"])
    p.add_argument("--raw-dir", default=str(config.RAW_DIR))
    p.add_argument("--force", action="store_true", help="replace an existing manifest (create only)")
    a = p.parse_args(argv)
    raw = Path(a.raw_dir)
    sys.exit(create(raw, a.force) if a.action == "create" else verify(raw))


if __name__ == "__main__":
    main()
